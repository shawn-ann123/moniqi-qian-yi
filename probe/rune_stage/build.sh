#!/bin/bash
# 编译打符探针。二进制输出到 RP-26Rune/output/（power_rune 库用 /proc/self/exe
# 相对路径找 config/power_rune.json，必须放这里）。
#   stage = 完整链路探针（NN/refiner/PnP + 后续全链，诊断用）
#   gt    = GT 真值版探针（识别模块输出边界 InactiveTargets 由真值直接构造，验证 PnP 之后链路）
# usage: build.sh [stage|gt|all]   （默认 all）
set -euo pipefail
WS="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
RP="${RP26_ROOT:-$WS/RP-26Rune}"
DEPS_ROOT="${RP26_DEPS_ROOT:-$HOME/.local/opt/rp26-deps}"
DEPS="$DEPS_ROOT/usr"
SIM="${DAEDALUS_SIM_ROOT:-/home/shawn/桌面/rm/daedalus-intel-optimized}"
SDK="${DAEDALUS_SIM_SDK_ROOT:-$SIM/sdk}"

if [[ ! -d "$DEPS/include" ]]; then
  echo "未找到外部依赖目录：$DEPS_ROOT" >&2
  exit 1
fi

if [[ ! -f "$RP/output/libpower_rune_lib.so" ]]; then
  echo "未找到 $RP/output/libpower_rune_lib.so，请先运行 $WS/build_all.sh" >&2
  exit 1
fi

build() {
  local src="$1" out="$2"
  /usr/bin/c++ -std=gnu++20 -O2 -fPIC \
    -I"$RP/src/core/algorithm/power_rune/config" \
    -I"$RP/src/core/algorithm/power_rune/include" \
    -I"$RP/src/core/algorithm/power_rune/interface" \
    -I"$RP/src/core/utility/time/inc" \
    -I"$RP/src/core/utility/threads/inc" \
    -I"$RP/src/core/utility/img_viz/inc" \
    -I"$RP/src/core/utility/transform_tools/inc" \
    -I"$RP/src/core/algorithm/function/inc" \
    -I"$RP/src/core/utility/foxglove/autogenerated_flatbuffers" \
    -I"$RP/src/core/utility/config_loader/inc" \
    -I"$RP/src/core/utility/foxglove_viz/inc" \
    -I"$RP/src/core/utility/foxglove/include" \
    -isystem /usr/include/eigen3 \
    -isystem /usr/include/opencv4 \
    -isystem "$DEPS/include" \
    -I"$SDK/include" \
    "$src" \
    -o "$out" \
    -L"$RP/output" \
    -lpower_rune_lib -ltransform_tools_lib -lconfig_loader_lib -lfunction_lib \
    -lfoxglove_viz -lfoxglove_lib -limg_viz_lib \
    -L"$DEPS/lib" -lopenvino \
    "$DEPS/lib/x86_64-linux-gnu/libglog.so.0.6.0" \
    "$DEPS/lib/x86_64-linux-gnu/libgflags.so.2.2.2" \
    "$DEPS/lib/x86_64-linux-gnu/libceres.so.2.2.0" \
    "$DEPS/lib/x86_64-linux-gnu/libfmt.so.10.1.0" \
    "$SDK/lib/libdaedalus_sim_sdk.a" \
    -lpthread \
    -lopencv_core -lopencv_imgproc -lopencv_imgcodecs -lopencv_calib3d -lopencv_features2d -lopencv_flann \
    -Wl,-rpath,"$RP/output:$DEPS/lib/x86_64-linux-gnu:$DEPS/lib"
  echo "built: $out"
}

target="${1:-all}"
case "$target" in
  stage) build "$WS/probe/rune_stage/rune_stage_probe.cpp" "$RP/output/rune_stage_probe" ;;
  gt)    build "$WS/probe/rune_stage/rune_stage_gt_probe.cpp" "$RP/output/rune_stage_gt_probe" ;;
  all)
    build "$WS/probe/rune_stage/rune_stage_probe.cpp" "$RP/output/rune_stage_probe"
    build "$WS/probe/rune_stage/rune_stage_gt_probe.cpp" "$RP/output/rune_stage_gt_probe"
    /usr/bin/c++ -std=gnu++20 -O2 \
      -I"$SDK/include" \
      "$WS/probe/rune_stage/sim_setup.cpp" \
      "$SDK/lib/libdaedalus_sim_sdk.a" -lpthread \
      -o "$RP/output/sim_setup"
    echo "built: $RP/output/sim_setup"
    ;;
  *) echo "usage: $0 [stage|gt|all]"; exit 1 ;;
esac
